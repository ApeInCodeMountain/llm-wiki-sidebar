// Build the served client bundle: lib/client.src.js + the vendored markdown-it
// UMD build, concatenated into lib/client.js.
//
// Why inline instead of `require('markdown-it')`: browser client bundles resolve
// only the frozen platform module table (react, cordis, dsh-client-store,
// dsh-client-ui-slots, dsh-client-ui-primitives, dsh-client-ui-dockkit) plus the
// boot graph rows. Node modules are not resolvable at runtime, so a third-party
// library must be shipped inside the bundle.
//
// The vendored file is markdown-it 14.1.0 (MIT); its license text sits beside it
// at lib/vendor/markdown-it.LICENSE.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const read = (rel) => readFileSync(fileURLToPath(new URL(rel, root)), "utf8");
const write = (rel, text) => writeFileSync(fileURLToPath(new URL(rel, root)), text);

const MARKER = "/*__LLMWIKI_MARKDOWN_IT__*/";
const source = read("lib/client.src.js");
if (!source.includes(MARKER)) {
  throw new Error("lib/client.src.js is missing the vendoring marker " + MARKER);
}

const vendor = read("lib/vendor/markdown-it.min.js");
// The UMD wrapper takes its CommonJS branch first; the local `module`/`exports`
// pair below keeps it from touching our outer module object or any global.
const inlined = [
  "const markdownit = (function () {",
  "\tvar module = { exports: {} };",
  "\tvar exports = module.exports;",
  vendor,
  "\treturn module.exports;",
  "})();",
].join("\n");

const header = [
  "// llm-wiki-sidebar — client half (GENERATED by scripts/build-client.mjs).",
  "//",
  "// Edit lib/client.src.js, then run `node scripts/build-client.mjs`.",
  "// Bundles markdown-it 14.1.0 (MIT, https://github.com/markdown-it/markdown-it);",
  "// its license text ships at lib/vendor/markdown-it.LICENSE.",
  "",
].join("\n");

write("lib/client.js", header + source.replace(MARKER, () => inlined));
console.log("lib/client.js written (" + (header.length + source.length + inlined.length) + " bytes)");
